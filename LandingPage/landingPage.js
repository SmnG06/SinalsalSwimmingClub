document.addEventListener('DOMContentLoaded', () => {
  const langSwitcher = document.getElementById('sinalSwimLangSwitcher');
  const langBtns = document.querySelectorAll('.sinalSwim-lang-btn');

  function applyLanguage(lang) {
    const dict = sinalSwimI18n[lang] || sinalSwimI18n.id;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.innerHTML = dict[key];
      }
    });

    if (langSwitcher) langSwitcher.setAttribute('data-selected', lang);
    langBtns.forEach((btn) => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    localStorage.setItem('sinalswim_lang', lang);
    document.documentElement.setAttribute('lang', lang);
  }

  const initialLang = localStorage.getItem('sinalswim_lang') || 'id';
  applyLanguage(initialLang);

  langBtns.forEach((btn) => {
    btn.addEventListener('click', () => {
      const selectedLang = btn.getAttribute('data-lang');
      applyLanguage(selectedLang);
    });
  });

  const slides = document.querySelectorAll('.sinalSwim-slide');
  const dotsContainer = document.getElementById('sinalSwimDotsContainer');
  const prevBtn = document.getElementById('sinalSwimPrevBtn');
  const nextBtn = document.getElementById('sinalSwimNextBtn');
  const heroSection = document.getElementById('hero');

  let currentSlide = 0;
  let sliderTimer = null;
  const slideDuration = 6000; 

  if (dotsContainer) {
    dotsContainer.innerHTML = '';
    slides.forEach((_, i) => {
      const dot = document.createElement('button');
      dot.className = `sinalSwim-slider-dot ${i === 0 ? 'active' : ''}`;
      dot.setAttribute('aria-label', `Slide ${i + 1}`);
      dot.addEventListener('click', () => {
        goToSlide(i);
        startAutoplay();
      });
      dotsContainer.appendChild(dot);
    });
  }

  const dots = document.querySelectorAll('.sinalSwim-slider-dot');

  function goToSlide(index) {
    slides.forEach((slide, i) => {
      slide.classList.toggle('active', i === index);

      const vid = slide.querySelector('video');
      if (vid) {
        if (i === index) {
          vid.play().catch(() => {});
        } else {
          vid.pause();
        }
      }
    });

    dots.forEach((dot, i) => {
      dot.classList.toggle('active', i === index);
    });

    currentSlide = index;
  }

  function nextSlide() {
    let nextIndex = (currentSlide + 1) % slides.length;
    goToSlide(nextIndex);
  }

  function prevSlide() {
    let prevIndex = (currentSlide - 1 + slides.length) % slides.length;
    goToSlide(prevIndex);
  }

  function startAutoplay() {
    stopAutoplay();
    sliderTimer = setInterval(nextSlide, slideDuration);
  }

  function stopAutoplay() {
    if (sliderTimer) clearInterval(sliderTimer);
  }

  if (nextBtn && prevBtn) {
    nextBtn.addEventListener('click', () => {
      nextSlide();
      startAutoplay();
    });

    prevBtn.addEventListener('click', () => {
      prevSlide();
      startAutoplay();
    });
  }

  let touchStartX = 0;
  let touchEndX = 0;

  if (heroSection) {
    heroSection.addEventListener('touchstart', (e) => {
      touchStartX = e.changedTouches[0].screenX;
    }, { passive: true });

    heroSection.addEventListener('touchend', (e) => {
      touchEndX = e.changedTouches[0].screenX;
      if (touchStartX - touchEndX > 50) {
        nextSlide();
        startAutoplay();
      } else if (touchEndX - touchStartX > 50) {
        prevSlide();
        startAutoplay();
      }
    }, { passive: true });
  }

  if (slides.length > 0) {
    goToSlide(0);
    startAutoplay();
  }

  const modalBackdrop = document.getElementById('sinalSwimModalBackdrop');
  const modalCloseBtn = document.getElementById('sinalSwimModalCloseBtn');
  const comingSoonElements = document.querySelectorAll('.sinalSwim-coming-soon');

  function openModal() {
    if (modalBackdrop) {
      modalBackdrop.classList.add('active');
      document.body.style.overflow = 'hidden';
    }
  }

  function closeModal() {
    if (modalBackdrop) {
      modalBackdrop.classList.remove('active');
      document.body.style.overflow = '';
    }
  }

  comingSoonElements.forEach((el) => {
    el.addEventListener('click', (e) => {
      e.preventDefault();
      openModal();
    });
  });

  if (modalCloseBtn) {
    modalCloseBtn.addEventListener('click', closeModal);
  }

  if (modalBackdrop) {
    modalBackdrop.addEventListener('click', (e) => {
      if (e.target === modalBackdrop) {
        closeModal();
      }
    });
  }
});